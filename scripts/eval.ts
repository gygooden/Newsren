// Runs the verification pipeline over saved briefings and recorded runs,
// prints a short report and writes docs/eval-results.md.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { assembleBriefing } from "../lib/agent/finalize";
import type { Briefing, RunRecord, SourceRecord } from "../lib/agent/types";
import { quoteIsSupported } from "../lib/agent/verify";

const read = <T>(p: string): T => JSON.parse(readFileSync(p, "utf8")) as T;
const sample = read<SourceRecord[]>("data/sample/local-news.json");
const real = [...read<SourceRecord[]>("data/real/federal-register.json"), ...read<SourceRecord[]>("data/real/arxiv.json")];
const corpus = [...real, ...sample];

interface Row {
  name: string;
  kind: "saved" | "recorded run" | "synthetic fixture";
  displayed: number;
  matched: number;
  removed: number;
  gaps: number;
  beyond: number;
  disagreements: number;
  steps?: number;
  toolCalls?: number;
  tokens?: number;
  cost?: number;
}

function measure(name: string, kind: Row["kind"], b: Briefing, removed: number): Row {
  const sources = new Map(Object.entries(b.sources));
  const claims = b.items.flatMap((i) => i.claims);
  const matched = claims.filter((c) => quoteIsSupported({ sourceId: c.sourceId, quote: c.quote }, sources).ok).length;
  return { name, kind, displayed: claims.length, matched, removed, gaps: b.gaps.length, beyond: b.beyond.length, disagreements: b.disagreements.length };
}

const rows: Row[] = [];

const saved = read<{ briefings: { sampleWatchId: string; briefing: Briefing }[] }>("data/generated/briefings.json");
for (const s of saved.briefings) {
  const removed = s.briefing.unverified.filter((u) => u.sourceId !== "").length;
  rows.push(measure(`saved: ${s.sampleWatchId}`, "saved", s.briefing, removed));
}

const runFiles = readdirSync("data/eval/runs").filter((f) => f.endsWith(".json"));
for (const f of runFiles) {
  const run = read<RunRecord>(`data/eval/runs/${f}`);
  const retrieved = new Map(run.retrieved.map((r) => [r.id, r]));
  const { briefing, verification } = assembleBriefing({
    id: run.id,
    watch: run.watch,
    question: run.question,
    submission: run.submission ?? { items: [] },
    retrieved,
    corpus,
    mode: "live",
    createdAt: run.createdAt,
  });
  const row = measure(`run: ${f}`, run.synthetic ? "synthetic fixture" : "recorded run", briefing, verification.stats.removedClaims);
  if (!run.synthetic) {
    row.steps = run.usage.steps;
    row.toolCalls = run.usage.toolCalls;
    row.tokens = run.usage.inputTokens + run.usage.outputTokens;
    row.cost = run.usage.estimatedCostUsd;
  }
  rows.push(row);
}

const sum = (k: keyof Row, rs = rows) => rs.reduce((n, r) => n + (Number(r[k]) || 0), 0);
const displayed = sum("displayed");
const matched = sum("matched");
const live = rows.filter((r) => r.kind === "recorded run");
const avg = (k: keyof Row) => (live.length ? (sum(k, live) / live.length).toFixed(k === "cost" ? 5 : 1) : "n/a (no recorded live runs yet)");

const lines = [
  "# Evaluation results",
  "",
  `Generated by \`npx tsx scripts/eval.ts\` on ${new Date().toISOString().slice(0, 10)}. Inputs: ${saved.briefings.length} saved briefings, ${live.length} recorded live runs, ${rows.filter((r) => r.kind === "synthetic fixture").length} synthetic fixtures.`,
  "",
  "Synthetic fixtures are hand-written test inputs, not model output. They are included to show that the verification gate removes unsupported claims, and they are excluded from the per-run averages.",
  "",
  "## Summary",
  "",
  `- Displayed claims with a matched quote: ${matched} of ${displayed} (${displayed ? ((100 * matched) / displayed).toFixed(1) : "0"}%; target 100%)`,
  `- Unsupported claims removed: ${sum("removed")}`,
  `- Coverage gaps found: ${sum("gaps")}`,
  `- Items in "Beyond your watch": ${sum("beyond")}`,
  `- Disagreements surfaced: ${sum("disagreements")}`,
  `- Average steps per live run: ${avg("steps")}`,
  `- Average tool calls per live run: ${avg("toolCalls")}`,
  `- Average tokens per live run: ${avg("tokens")}`,
  `- Average estimated cost per live run (USD): ${avg("cost")}`,
  "",
  "## Per input",
  "",
  "| Input | Kind | Displayed claims | Matched | Removed | Gaps | Beyond | Disagreements |",
  "| --- | --- | --- | --- | --- | --- | --- | --- |",
  ...rows.map((r) => `| ${r.name} | ${r.kind} | ${r.displayed} | ${r.matched} | ${r.removed} | ${r.gaps} | ${r.beyond} | ${r.disagreements} |`),
  "",
  "To add recorded runs, run live research on the briefing page, use \"Download run record\", and save the file in `data/eval/runs/`.",
  "",
];
const report = lines.join("\n");
writeFileSync("docs/eval-results.md", report);
console.log(report);
